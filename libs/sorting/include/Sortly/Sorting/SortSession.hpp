#pragma once

#include "Sortly/Sorting/Algorithms/SortAlgorithm.hpp"
#include "Sortly/Sorting/Data/DataSet.hpp"
#include "Sortly/Sorting/Data/DataSetConfig.hpp"
#include "Sortly/Sorting/Operations/SortOperation.hpp"
#include "Sortly/Sorting/Operations/SortPlayback.hpp"
#include "Sortly/Sorting/Operations/SortStatistics.hpp"

#include <atomic>
#include <chrono>
#include <cstdint>
#include <memory>
#include <random>
#include <span>
#include <string_view>
#include <vector>

namespace Sortly {

/// @brief Encapsulates the complete state of a sorting execution.
///
/// A session owns the dataset being processed, the sequence of recorded
/// operations generated by the algorithm, the collected statistics and the
/// playback used to replay them.
///
/// A SortSession has no knowledge of windows, rendering or ImGui - the
/// visualization layer only ever reads from it through its getters. The
/// architecture assumes N sessions can exist and run independently at the
/// same time (e.g. std::vector<SortSession> sessions;) for side-by-side
/// algorithm comparison, so no state here is shared or global.
///
/// Ownership: every member is held by value (or unique_ptr) and nothing points into
/// a sibling member, so the compiler-generated move is correct.
class SortSession
{
public:
    /// @brief Outcome of a (possibly partial) computeOperations() call.
    enum class ComputeStatus
    {
        Complete,   // The algorithm finished; getOperations()/getStatistics() are final.
        InProgress, // The time budget ran out before the algorithm finished; call again to resume.
        Failed      // See getLastComputeError() for the reason.
    };

    /// @brief Why the last computeOperations() call failed. The caller decides what to tell the
    /// user; the library's logs are diagnostics for developers, not the way errors are reported.
    enum class ComputeError
    {
        None,                // The last call did not fail.
        NoAlgorithm,         // setAlgorithm() was never called.
        NoData,              // The dataset is empty: buildDataSet() was never called, or it yielded nothing.
        TooLargeForBlocking, // Blocking run over more than DataSetConfig::kQuadraticSafeLimit elements; pass a budget.
        AlgorithmThrew       // The algorithm threw while loading or stepping; partial results were discarded.
    };

    SortSession() : m_SessionId(s_NextSessionId.fetch_add(1, std::memory_order_relaxed)) {}

    SortSession(SortSession&&) noexcept = default;
    SortSession& operator=(SortSession&&) noexcept = default;

    // Copying is disabled rather than defined: a real copy would need to decide whether
    // in-flight compute state (m_ComputeInProgress) and the algorithm's cursor should be
    // duplicated or reset, which has no obviously correct default. Add an explicit
    // clone()-style method later if a real use case appears.
    SortSession(const SortSession&) = delete;
    SortSession& operator=(const SortSession&) = delete;

    //================================================//
    //               CONFIGURATION
    //================================================//

    /// @brief Stores the dataset configuration used by future buildDataSet() calls.
    /// Does not rebuild the dataset itself.
    void setDataSetConfig(const DataSetConfig& config);

    /// @brief Replaces the current algorithm.
    /// Clears any operations recorded for the previous one, as they no longer apply.
    void setAlgorithm(std::unique_ptr<SortAlgorithm> algorithm);

    //================================================//
    //                DATA MANAGEMENT
    //================================================//

    /// @brief (Re)builds the dataset from the current config using the given RNG engine.
    /// Clears any recorded operations.
    /// @return True if a non-empty dataset was generated, false otherwise (state unchanged).
    bool buildDataSet(std::mt19937& rng);

    /// @brief Shuffles the current dataset in place using the given RNG engine.
    /// Clears any previously recorded operations, as they were computed against the pre-shuffle order.
    void shuffleData(std::mt19937& rng);

    //================================================//
    //              OPERATION MANAGEMENT
    //================================================//

    /// @brief Runs the current algorithm over the dataset, recording every operation and
    /// statistic, up to an optional time budget. Call repeatedly with the same budget to resume a
    /// computation left InProgress by a previous call - the algorithm's own step cursor is preserved.
    /// @param budget Maximum wall-clock time to spend stepping the algorithm before yielding back to
    /// the caller (checked every few hundred steps, so it can be slightly overshot; each call
    /// always makes progress). Zero means "run to completion" (blocking), which also enables the
    /// DataSetConfig::kQuadraticSafeLimit bail-out - whether starting fresh or force-completing a
    /// computation left in progress by a prior budgeted call.
    /// @return Complete, InProgress (call again to continue) or Failed (the reason is in
    /// getLastComputeError()). Both are cached and retrievable at any time.
    ComputeStatus computeOperations(std::chrono::microseconds budget = std::chrono::microseconds::zero());

    /// @brief Discards recorded operations, statistics, compute state and the loaded playback,
    /// and releases the memory they held. Called whenever the session's data or algorithm changes.
    void clearOperations();

    /// @brief Loads the computed operations into this session's playback, starting from the
    /// session's dataset.
    /// @return False if nothing has been computed yet or a budgeted computation is still in progress.
    bool loadPlayback();

    /// @brief Computes operations to completion (if needed) and loads them into this
    /// session's playback. Always blocking - use computeOperations() directly for cooperative
    /// (budgeted) computation instead.
    bool preparePlayback();

    /// @brief True while a budgeted computeOperations() call is waiting to be resumed.
    [[nodiscard]] bool isComputing() const { return m_ComputeInProgress; }

    //================================================//
    //                    GETTERS
    //================================================//

    /// @brief The data the operations were (or will be) computed against. Never touched by playback.
    [[nodiscard]] const DataSet& getDataSet() const { return m_DataSet; }
    [[nodiscard]] const DataSetConfig& getDataSetConfig() const { return m_Config; }

    /// @brief What a view should draw right now: the playback's state once operations are
    /// loaded, otherwise the raw dataset.
    [[nodiscard]] std::span<const int> getVisualData() const
    {
        if (m_Playback.isLoaded())
            return m_Playback.getVisualData();
        return m_DataSet.values();
    }

    [[nodiscard]] const std::vector<SortOperation>& getOperations() const { return m_Operations; }
    [[nodiscard]] const SortStatistics& getStatistics() const { return m_Statistics; }

    [[nodiscard]] SortPlayback& getPlayback() { return m_Playback; }
    [[nodiscard]] const SortPlayback& getPlayback() const { return m_Playback; }

    [[nodiscard]] uint32_t getSessionId() const { return m_SessionId; }

    /// @brief Outcome of the most recent computeOperations() call.
    /// Reset to `Complete` by clearOperations(), so a stale Failed/InProgress never
    /// lingers after the session's data or algorithm changes.
    [[nodiscard]] ComputeStatus getLastComputeStatus() const { return m_LastComputeStatus; }

    /// @brief Reason for the most recent Failed status; None if the last call did not fail.
    /// Reset by clearOperations() together with the status.
    [[nodiscard]] ComputeError getLastComputeError() const { return m_LastComputeError; }

    //================================================//
    //              ALGORITHM INFORMATION
    //================================================//

    [[nodiscard]] std::string_view getAlgorithmName() const
    {
        return m_Algorithm ? m_Algorithm->getName() : "None";
    }
    [[nodiscard]] std::string_view getAlgorithmComplexity() const
    {
        return m_Algorithm ? m_Algorithm->getComplexity() : "N/A";
    }
    [[nodiscard]] std::string_view getAlgorithmDescription() const
    {
        return m_Algorithm ? m_Algorithm->getDescription() : "No algorithm selected.";
    }

private:
    uint32_t m_SessionId;
    // Monotonic counter; never reused, even across moves/destruction. Atomic so sessions
    // can be created from different threads.
    static inline std::atomic<uint32_t> s_NextSessionId{0};

    DataSet m_DataSet;
    DataSetConfig m_Config;
    std::unique_ptr<SortAlgorithm> m_Algorithm;

    std::vector<SortOperation> m_Operations;
    SortStatistics m_Statistics;

    SortPlayback m_Playback;

    /// Records a failure (status + reason) and returns Failed.
    ComputeStatus fail(ComputeError error);

    ComputeStatus m_LastComputeStatus = ComputeStatus::Complete;
    ComputeError  m_LastComputeError  = ComputeError::None;
    bool m_ComputeInProgress = false;
};

/// @brief Enumerator name of a compute error (for logs and for mapping to UI messages).
[[nodiscard]] constexpr std::string_view toString(SortSession::ComputeError error) noexcept
{
    switch (error)
    {
        case SortSession::ComputeError::None:                return "None";
        case SortSession::ComputeError::NoAlgorithm:         return "NoAlgorithm";
        case SortSession::ComputeError::NoData:              return "NoData";
        case SortSession::ComputeError::TooLargeForBlocking: return "TooLargeForBlocking";
        case SortSession::ComputeError::AlgorithmThrew:      return "AlgorithmThrew";
    }
    return "Unknown";
}

} // namespace Sortly
